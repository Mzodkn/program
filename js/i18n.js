const STORAGE_KEY = 'itHub_lang';
let current = 'ar';

export function getLang() {
  return current;
}

export function t(key) {
  const dict = dictionaries[current] || dictionaries.ar;
  if (dict[key] != null) return dict[key];
  if (dictionaries.en[key] != null) return dictionaries.en[key];
  return key;
}

// Fill {placeholders} in a translated string.
export function tf(key, values = {}) {
  return String(t(key)).replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'ar';
  const dict = dictionaries[current];

  document.documentElement.lang = current;
  document.documentElement.dir = dict.dir;

  try {
    localStorage.setItem(STORAGE_KEY, current);
  } catch (err) {
    // Storage may be unavailable; the app still works for this session.
  }

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] != null) el.textContent = dict[key];
  });

  const btn = document.getElementById('langBtn');
  if (btn) {
    btn.textContent = dict.langButton;
    btn.setAttribute('aria-label', dict.langButton);
  }

  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: current } }));
}

export function initLang() {
  let stored = null;
  try {
    stored = localStorage.getItem(STORAGE_KEY);
  } catch (err) {
    // Ignore storage errors and fall back to Arabic.
  }
  setLang(stored === 'en' ? 'en' : 'ar');
}
